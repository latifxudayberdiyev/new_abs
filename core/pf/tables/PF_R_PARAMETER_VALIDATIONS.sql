COMMENT ON COLUMN PF_R_PARAMETER_VALIDATIONS.ID IS 'Bog''lanish identifikatori';
COMMENT ON COLUMN PF_R_PARAMETER_VALIDATIONS.PARAMETER_ID IS 'Tekshiriladigan parametr';
COMMENT ON COLUMN PF_R_PARAMETER_VALIDATIONS.FUNCTION_ID IS 'Qo''llaniladigan funksiya';
COMMENT ON COLUMN PF_R_PARAMETER_VALIDATIONS.CONFIG IS 'Funksiya argumentlari JSON ko''rinishida, masalan {"min":18,"max":65}';
COMMENT ON COLUMN PF_R_PARAMETER_VALIDATIONS.ML_ERROR_CODE IS 'Xato matnining ml kodi';
