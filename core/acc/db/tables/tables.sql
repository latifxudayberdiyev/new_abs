-- Manba: fabrika-produktov.html — "Тип счёта" ro'yxat oynasi, uning
--        "Изменение/Новый тип счёта" formasi, ochiladigan "дочерняя запись"
--        (Тип клиента / Коды COA / Валюта) formasi va "История изменений" oynasi.
--
-- Uslub avvalgi "Fizik shaxs mijoz kartochkasi" skripti bilan bir xil:
--   1) Jadval nomlari inglizcha ko'plikda
--   2) Har bir ma'lumot alohida atomik ustunda (birlashtirilgan ustun yo'q)
--   3) Nomenklatura xarakteridagi ma'lumotlar (Modul, Hisob sinflari spravochnigi)
--      alohida ACC_R_ prefiksli jadvallarga chiqarilgan
--   4) Barcha cheklovlar (PK/FK/UNIQUE/CHECK) CREATE TABLE ichida emas, balki
--      alohida ALTER TABLE ... ADD CONSTRAINT operatorlari orqali qo'shiladi,
--      nomlash: <JADVAL>_PK, <JADVAL>_F1.._Fn, <JADVAL>_U1.._Un, <JADVAL>_C1.._Cn
--   5) Har bir jadvalning cheklovlari va indekslari o'sha jadvalning CREATE TABLE
--      bayonotidan darhol keyin joylashtirilgan (indekslar: <JADVAL>_I1, _I2 ...)
--
-- Prefikslar:
--   ACC_R_  — spravochnik (ma'lumotnoma) jadvallari: Modul, Hisob sinflari katalogi
--   ACC_    — "Тип счёта" ierarxik spravochnigiga tegishli asosiy jadvallar
--             (ota yozuv, dochernie zapisi, o'zgarishlar tarixi)
--------------------------------------------------------------------------------


--================================================================================
-- QISM A. SPRAVOCHNIK (MA'LUMOTNOMA) JADVALLARI — prefiks ACC_R_
-- Har bir jadval blokida: CREATE TABLE -> COMMENT -> cheklovlar (ALTER TABLE) -> indekslar
--================================================================================

--------------------------------------------------------------------------------
-- A1) ACC_R_MODULES — Bank moduli spravochnigi (Kredit, Depozit, Karta va h.k.)
--------------------------------------------------------------------------------
CREATE TABLE ACC_R_MODULES (
  MODULE_CODE  VARCHAR2(10)   NOT NULL,
  MODULE_NAME  VARCHAR2(100)  NOT NULL
);

COMMENT ON TABLE ACC_R_MODULES IS 'Bank modullari spravochnigi. "Тип счёта" formasidagi "Модуль" tanlov ro''yxatiga (LN, DEP, SV, CARD, GUAR, MT, UTIL, FX) mos keladi.';
COMMENT ON COLUMN ACC_R_MODULES.MODULE_CODE IS 'Modul kodi (PK), masalan "DEP"';
COMMENT ON COLUMN ACC_R_MODULES.MODULE_NAME IS 'Modul nomi, masalan "Депозит"';

-- ACC_R_MODULES: cheklovlar (constraints)
ALTER TABLE ACC_R_MODULES ADD CONSTRAINT ACC_R_MODULES_PK PRIMARY KEY (MODULE_CODE);


--------------------------------------------------------------------------------
-- A2) ACC_R_CLASS_CATALOG — "Типы счетов — справочник" oynasi
--    (bank sohasida qabul qilingan balansli hisoblar sinflarining namunaviy
--    tarkibi; ma'lumotnoma xarakterida, "Тип счёта" yozuvlariga FK bilan
--    bog'lanmagan — faqat mo'ljal/namuna sifatida ko'rsatiladi)
--------------------------------------------------------------------------------
CREATE TABLE ACC_R_CLASS_CATALOG (
  CATALOG_ID    NUMBER(19)     GENERATED BY DEFAULT AS IDENTITY,
  CLASS_CODE    VARCHAR2(2)    NOT NULL,
  RANGE_FROM    VARCHAR2(10)   NOT NULL,
  RANGE_TO      VARCHAR2(10)   NOT NULL,
  CATALOG_NAME  VARCHAR2(200)  NOT NULL,
  CATALOG_DESC  VARCHAR2(500)
);

COMMENT ON TABLE ACC_R_CLASS_CATALOG IS
  '"Типы счетов — справочник" oynasidagi namunaviy hisob sinflari ro''yxati
   (masalan Sinf 2: "Depozit hisoblari", diapazon 20400-20499). Illyustrativ
   ma''lumotnoma, "Тип счёта" ierarxiyasiga bevosita bog''lanmagan.';

COMMENT ON COLUMN ACC_R_CLASS_CATALOG.CATALOG_ID   IS 'Katalog yozuvining unikal identifikatori (PK) — bitta sinf (CLASS_CODE) bo''yicha bir nechta diapazon bo''lishi mumkinligi uchun alohida surrogat kalit';
COMMENT ON COLUMN ACC_R_CLASS_CATALOG.CLASS_CODE   IS 'Hisob sinfi raqami ("Класс" ustuni), masalan "2"';
COMMENT ON COLUMN ACC_R_CLASS_CATALOG.RANGE_FROM   IS 'Hisoblar diapazonining boshlanishi ("Диапазон счетов" ustunidan ajratilgan, masalan "20101")';
COMMENT ON COLUMN ACC_R_CLASS_CATALOG.RANGE_TO     IS 'Hisoblar diapazonining tugashi ("Диапазон счетов" ustunidan ajratilgan, masalan "20999")';
COMMENT ON COLUMN ACC_R_CLASS_CATALOG.CATALOG_NAME IS 'Sinf nomi ("Наименование" ustuni), masalan "Наличность и драгоценные металлы"';
COMMENT ON COLUMN ACC_R_CLASS_CATALOG.CATALOG_DESC IS 'Sinf tavsifi ("Описание" ustuni)';

-- ACC_R_CLASS_CATALOG: cheklovlar (constraints)
ALTER TABLE ACC_R_CLASS_CATALOG ADD CONSTRAINT ACC_R_CLASS_CATALOG_PK PRIMARY KEY (CATALOG_ID);


--------------------------------------------------------------------------------
-- A3) ACC_R_CLASS_CATALOG_MODULES — Sinf <-> Modul bog'lanish jadvali (N:N)
--    ("Обычно используется в модулях" ustuni bir nechta modulni bir vergul
--    bilan sanab o'tgani uchun ko'p-ko'pga bog'lanish sifatida ajratilgan)
--------------------------------------------------------------------------------
CREATE TABLE ACC_R_CLASS_CATALOG_MODULES (
  CATALOG_ID   NUMBER(19)    NOT NULL,
  MODULE_CODE  VARCHAR2(10)  NOT NULL
);

COMMENT ON TABLE ACC_R_CLASS_CATALOG_MODULES IS
  'ACC_R_CLASS_CATALOG va ACC_R_MODULES orasidagi ko''p-ko''pga (N:N) bog''lanish
   jadvali — "Обычно используется в модулях" ustunidagi ro''yxat (masalan
   "CARD, DEP") shu jadvalda alohida-alohida qatorlarda saqlanadi.';

COMMENT ON COLUMN ACC_R_CLASS_CATALOG_MODULES.CATALOG_ID  IS 'Hisob sinfi katalog yozuvi, FK -> ACC_R_CLASS_CATALOG.CATALOG_ID';
COMMENT ON COLUMN ACC_R_CLASS_CATALOG_MODULES.MODULE_CODE IS 'Modul kodi, FK -> ACC_R_MODULES.MODULE_CODE';

-- ACC_R_CLASS_CATALOG_MODULES: cheklovlar (constraints)
ALTER TABLE ACC_R_CLASS_CATALOG_MODULES ADD CONSTRAINT ACC_R_CLASS_CATALOG_MODULES_PK PRIMARY KEY (CATALOG_ID, MODULE_CODE);
ALTER TABLE ACC_R_CLASS_CATALOG_MODULES ADD CONSTRAINT ACC_R_CLASS_CATALOG_MODULES_F1 FOREIGN KEY (CATALOG_ID) REFERENCES ACC_R_CLASS_CATALOG (CATALOG_ID) ON DELETE CASCADE;
ALTER TABLE ACC_R_CLASS_CATALOG_MODULES ADD CONSTRAINT ACC_R_CLASS_CATALOG_MODULES_F2 FOREIGN KEY (MODULE_CODE)  REFERENCES ACC_R_MODULES (MODULE_CODE);

-- ACC_R_CLASS_CATALOG_MODULES: indekslar
CREATE INDEX ACC_R_CLASS_CATALOG_MODULES_I1 ON ACC_R_CLASS_CATALOG_MODULES (MODULE_CODE);


